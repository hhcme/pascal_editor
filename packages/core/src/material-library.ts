type SolidMaterialCatalogItemOptions = Omit<
  MaterialCatalogItem,
  'preset' | 'previewColor' | 'previewShape' | 'source'
> & {
  color: string
  roughness: number
  metalness?: number
  opacity?: number
  transparent?: boolean
  previewColor?: string
  previewShape?: MaterialCatalogPreviewShape
  source?: MaterialCatalogSource
  mapProperties?: Partial<MaterialMapProperties>
}

function solidMaterialCatalogItem({
  color,
  roughness,
  metalness = 0,
  opacity = 1,
  transparent,
  previewColor,
  previewShape = 'tile',
  source = 'public',
  mapProperties,
  ...item
}: SolidMaterialCatalogItemOptions): MaterialCatalogItem {
  return {
    ...item,
    source,
    previewColor: previewColor ?? color,
    previewShape,
    preset: {
      maps: {},
      mapProperties: {
        color,
        roughness,
        metalness,
        repeatX: 1,
        repeatY: 1,
        rotation: 0,
        wrapS: 'Repeat',
        wrapT: 'Repeat',
        normalScaleX: 1,
        normalScaleY: 1,
        emissiveIntensity: 1,
        displacementScale: 0.02,
        transparent: transparent ?? opacity < 1,
        flipY: true,
        bumpScale: 1,
        emissiveColor: '#000000',
        aoMapIntensity: 1,
        side: 0,
        opacity,
        lightMapIntensity: 1,
        ...mapProperties,
      },
    },
  }
}

type TextureMaterialCatalogItemOptions = Omit<MaterialCatalogItem, 'preset' | 'source'> & {
  maps: MaterialPresetPayload['maps']
  color?: string
  roughness?: number
  metalness?: number
  opacity?: number
  transparent?: boolean
  source?: MaterialCatalogSource
  mapProperties?: Partial<MaterialMapProperties>
}

